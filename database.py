"""SQLite database layer (plain sqlite3 – no ORM needed, easy to explain in viva)."""
import os
import sqlite3

from flask import g

BASE = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(BASE, "instance", "healthcare.db")

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    full_name     TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    age           INTEGER,
    gender        TEXT,
    phone         TEXT,
    created_at    TEXT NOT NULL DEFAULT (datetime('now','localtime'))
);

CREATE TABLE IF NOT EXISTS login_logs (
    id        INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id   INTEGER REFERENCES users(id) ON DELETE CASCADE,
    email     TEXT,
    success   INTEGER NOT NULL,
    ip        TEXT,
    logged_at TEXT NOT NULL DEFAULT (datetime('now','localtime'))
);

CREATE TABLE IF NOT EXISTS reports (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id        INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    original_name  TEXT NOT NULL,
    stored_name    TEXT NOT NULL,
    scan_method    TEXT,
    ocr_text       TEXT,
    extracted_json TEXT,
    file_data BLOB,
    uploaded_at    TEXT NOT NULL DEFAULT (datetime('now','localtime'))
);

CREATE TABLE IF NOT EXISTS predictions (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id       INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    report_id     INTEGER REFERENCES reports(id) ON DELETE SET NULL,
    disease       TEXT NOT NULL,
    inputs_json   TEXT NOT NULL,
    probability   REAL NOT NULL,
    risk_level    TEXT NOT NULL,
    result_json   TEXT NOT NULL,
    model_name    TEXT,
    source        TEXT NOT NULL DEFAULT 'manual',
    created_at    TEXT NOT NULL DEFAULT (datetime('now','localtime'))
);

CREATE INDEX IF NOT EXISTS idx_pred_user ON predictions(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_rep_user ON reports(user_id);
"""


DATABASE_URL = os.environ.get("DATABASE_URL")
if os.environ.get("VERCEL") and not DATABASE_URL:
    raise RuntimeError("Set DATABASE_URL in Vercel environment variables")

class PostgresConnection:
    def __init__(self):
        import psycopg
        from psycopg.rows import dict_row
        self.con = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)

    def execute(self, sql, params=()):
        sql = sql.replace("?", "%s")
        return self.con.execute(sql, params)

    def commit(self):
        self.con.commit()

    def close(self):
        self.con.close()


def connect():
    if DATABASE_URL:
        return PostgresConnection()
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    con = sqlite3.connect(DB_PATH)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys = ON")
    return con


def get_db():
    if "db" not in g:
        g.db = connect()
    return g.db


def close_db(_exc=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db():
    con = connect()
    try:
        if DATABASE_URL:
            schema = SCHEMA.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY").replace("(datetime('now','localtime'))", "(to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))").replace("BLOB", "BYTEA")
            con.execute("SELECT pg_advisory_xact_lock(78123456)")
            for statement in schema.split(";"):
                if statement.strip():
                    con.execute(statement)
            con.execute("ALTER TABLE reports ADD COLUMN IF NOT EXISTS file_data BYTEA")
        else:
            con.executescript(SCHEMA)
            if not any(r['name'] == 'file_data' for r in con.execute("PRAGMA table_info(reports)")):
                con.execute("ALTER TABLE reports ADD COLUMN file_data BLOB")
        con.commit()
    finally:
        con.close()
